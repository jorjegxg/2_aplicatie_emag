-- Boții cu voce (serviciul `boti`): doar citesc din Base / eMAG / Trendyol și îți spun ce au găsit.
CREATE TABLE IF NOT EXISTS boti (
  id TEXT PRIMARY KEY,
  nume TEXT NOT NULL,
  descriere TEXT,
  activ BOOLEAN NOT NULL DEFAULT false,
  -- {zile:[1..7], ora_start:"HH:MM", ora_stop:"HH:MM"|null, interval_min, durata_max_min}
  program JSONB NOT NULL DEFAULT '{}',
  -- {id:"piper:liana-high", viteza:1}
  voce JSONB NOT NULL DEFAULT '{}',
  model TEXT NOT NULL DEFAULT 'sonnet',
  -- {max_produse, tari:[...], ...}
  setari JSONB NOT NULL DEFAULT '{}',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS boti_rulari (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bot_id TEXT NOT NULL REFERENCES boti(id) ON DELETE CASCADE,
  declansat TEXT NOT NULL DEFAULT 'manual',
  status TEXT NOT NULL DEFAULT 'ruleaza' CHECK (status IN ('ruleaza', 'gata', 'eroare', 'oprit')),
  progres TEXT,
  eroare TEXT,
  rezumat TEXT,
  constatari JSONB NOT NULL DEFAULT '[]',
  text_vorbit TEXT,
  audio TEXT,
  cost_usd NUMERIC(10, 4),
  citit BOOLEAN NOT NULL DEFAULT false,
  inceput TIMESTAMPTZ NOT NULL DEFAULT now(),
  sfarsit TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS boti_rulari_bot_idx ON boti_rulari (bot_id, inceput DESC);

-- O conversație = tu și un bot, de obicei pe un raport (rulare_id); session_id = sesiunea Claude reluată.
CREATE TABLE IF NOT EXISTS boti_conversatii (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bot_id TEXT NOT NULL REFERENCES boti(id) ON DELETE CASCADE,
  rulare_id INTEGER REFERENCES boti_rulari(id) ON DELETE SET NULL,
  session_id TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS boti_mesaje (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversatie_id INTEGER NOT NULL REFERENCES boti_conversatii(id) ON DELETE CASCADE,
  rol TEXT NOT NULL CHECK (rol IN ('eu', 'bot')),
  text TEXT NOT NULL,
  audio TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS boti_mesaje_conv_idx ON boti_mesaje (conversatie_id, id);

-- Ce a văzut botul SEO la o căutare: sugestii, câte rezultate, în ce categorii, primii concurenți.
CREATE TABLE IF NOT EXISTS boti_keywords (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  termen TEXT NOT NULL,
  platforma TEXT NOT NULL,
  sugestii JSONB NOT NULL DEFAULT '[]',
  nr_rezultate INTEGER,
  categorii JSONB NOT NULL DEFAULT '[]',
  top JSONB NOT NULL DEFAULT '[]',
  vazut_la TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS boti_keywords_termen_idx ON boti_keywords (platforma, termen, vazut_la DESC);

-- Setări (contul Claude criptat, cursoarele boților).
CREATE TABLE IF NOT EXISTS boti_setari (
  cheie TEXT PRIMARY KEY,
  valoare TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

